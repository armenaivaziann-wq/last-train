import json, os

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")


def load(n):
    return json.load(open(os.path.join(ROOT, f"data/cases/level_{n:02d}.json")))


def save(n, d):
    json.dump(d, open(os.path.join(ROOT, f"data/cases/level_{n:02d}.json"), "w"), ensure_ascii=False, indent=1)


def clue(d, cid, typ, title, text, points=(), **extra):
    d["clues"][cid] = dict({"type": typ, "title": title, "text": text, "points_to": list(points)}, **extra)


def dlg(d, npc):
    return d["dialogues"].setdefault(npc, {"greet": "...", "topics": []})


def topic(d, npc, tid, q, a, gives=(), **cond):
    t = dlg(d, npc)
    t.setdefault("topics", [])
    t["topics"] = [x for x in t["topics"] if x["id"] != tid]
    t["topics"].append(dict({"id": tid, "q": q, "a": a, "gives": list(gives)}, **cond))


def reaction(d, npc, cid, a, gives=(), state=None):
    r = {"a": a, "gives": list(gives)}
    if state:
        r["state"] = state
    dlg(d, npc).setdefault("reactions", {})[cid] = r


def deduction(d, res, a, b, refutes=()):
    d["deductions"] = [x for x in d["deductions"] if x["result"] != res]
    x = {"result": res, "a": list(a), "b": list(b)}
    if refutes:
        x["refutes"] = list(refutes)
    d["deductions"].append(x)


def luggage_item(d, npc, title, name, text, label, htext, cid, hidden=False):
    lg = d.setdefault("luggage", {}).setdefault(npc, {"title": title, "items": []})
    lg["items"] = [i for i in lg["items"] if i.get("hotspot", {}).get("clue") != cid]
    h = {"label": label, "text": htext, "clue": cid}
    if hidden:
        h["hidden"] = True
    lg["items"].append({"name": name, "text": text, "hotspot": h})


def item(d, iid, car, pos, sprite, label, title, text, hots, radius=24):
    d["extra_items"] = [i for i in d.get("extra_items", []) if i["id"] != iid]
    d["extra_items"].append({"id": iid, "carriage": car, "pos": pos, "sprite": sprite, "label": label, "radius": radius})
    d["objects"][iid] = {"title": title, "kind": "item", "text": text, "hotspots": hots}


def hot(label, text, cid, hidden=False):
    h = {"id": cid, "label": label, "text": text, "clue": cid}
    if hidden:
        h["hidden"] = True
    return h


def secret(d, npc, lie_id, q, lie_answer, lie_title, lie_text, ev_id, ev_title, ev_text, res_id, res_title, res_text,
           confess, res_points=()):
    """Невиновный с тайной: лжёт на допросе (показание против себя), улика разоблачает ложь,
    вывод «Не убийца, но скрывал…» опровергает ложь и снимает с него подозрение."""
    clue(d, lie_id, "testimony", lie_title, lie_text, [npc])
    topic(d, npc, lie_id.replace("s_", "t_"), q, lie_answer, [lie_id])
    clue(d, res_id, "contradiction", res_title, res_text, res_points)
    deduction(d, res_id, [lie_id], [ev_id], refutes=[lie_id])
    reaction(d, npc, ev_id, confess, state="scared")
    d.setdefault("initial_states", {}).setdefault(npc, "suspicious")


def alibi(d, cid, npc, frm, to, car):
    d["clues"][cid]["alibi"] = {"npc": npc, "from": frm, "to": to, "carriage": car}


def hide_hotspot(d, oid, hid):
    for h in d["objects"][oid]["hotspots"]:
        if h.get("id") == hid:
            h["hidden"] = True


def story(d, ev):
    d["story_events"] = [e for e in d.get("story_events", []) if e["id"] != ev["id"]]
    d["story_events"].append(ev)


def late_kill(d, eid, at, unless_key, npc, item_def, obj, title, text):
    """Второе преступление, если игрок тянет: подозреваемый выбывает, появляется новая улика."""
    story(d, {"id": eid, "trigger": {"at": at, "unless_key": unless_key}, "effects": [
        {"type": "kill", "npc": npc, "item": item_def, "title": title, "text": text},
        {"type": "sound", "name": "discovery_stinger"}]})
    d["objects"][item_def["id"]] = obj


